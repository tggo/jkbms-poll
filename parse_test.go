func near(t *testing.T, name string, got, want, tol float64) {
	t.Helper()
	if math.Abs(got-want) > tol {
		t.Errorf("%s: got %v, want %v (±%v)", name, got, want, tol)
	}
}

func TestParseJK02_V15_Frame(t *testing.T) {
	if len(cellInfoJK02_32S_V15) != 300 {
		t.Fatalf("fixture length %d, want 300", len(cellInfoJK02_32S_V15))
	}
	r, err := ParseJK02CellInfo(cellInfoJK02_32S_V15, 16, "test:bms")
	if err != nil {
		t.Fatalf("parse: %v", err)
	}

	if !r.CRCOK {
		t.Errorf("CRC mismatch on a known-good frame; computed != byte 299")
	}
	if r.FrameType != 0x02 {
		t.Errorf("FrameType = 0x%02x, want 0x02", r.FrameType)
	}

	// Cell voltages — expected via upstream test:
	// cell #1 = 3.333 V, cell #13 (min) = 3.320 V, cell #16 (max) = 3.337 V
	near(t, "cell[0]", r.CellVoltagesV[0], 3.333, 0.001)
	near(t, "cell[12]", r.CellVoltagesV[12], 3.320, 0.001)
	near(t, "cell[15]", r.CellVoltagesV[15], 3.337, 0.001)

	// Stats
	near(t, "min_cell_v", r.CellMinV, 3.320, 0.001)
	near(t, "max_cell_v", r.CellMaxV, 3.337, 0.001)
	near(t, "delta_cell_v", r.CellDeltaV, 0.017, 0.001)
	if r.CellMinNum != 13 {
		t.Errorf("CellMinNum = %d, want 13", r.CellMinNum)
	}
	if r.CellMaxNum != 16 {
		t.Errorf("CellMaxNum = %d, want 16", r.CellMaxNum)
	}

	// Battery
	near(t, "battery_v", r.BatteryVoltageV, 53.224, 0.001)
	near(t, "battery_a", r.BatteryCurrentA, 31.881, 0.001)

	// Temperatures
	near(t, "t1_c", r.T1C, 13.4, 0.05)
	near(t, "t2_c", r.T2C, 12.8, 0.05)
	near(t, "mos_temp", r.PowerTubeTempC, 12.9, 0.05)

	// SOC and capacity
	if r.SOCPercent != 25 {
		t.Errorf("SOC = %d, want 25", r.SOCPercent)
	}
	near(t, "remaining_ah", r.RemainingAh, 49.286, 0.001)
	near(t, "nominal_ah", r.NominalAh, 200.000, 0.001)
	if r.CycleCount != 9 {
		t.Errorf("CycleCount = %d, want 9", r.CycleCount)
	}

	// Total runtime (per upstream test: 24530060 s)
	if r.TotalRuntimeS != 24530060 {
		t.Errorf("TotalRuntimeS = %d, want 24530060", r.TotalRuntimeS)
	}

	// Charging + discharging mosfets — both on per upstream test
	if !r.Charging {
		t.Errorf("Charging=false, want true")
	}
	if !r.Discharging {
		t.Errorf("Discharging=false, want true")
	}
}

func TestParse_RejectsBadHeader(t *testing.T) {
	buf := make([]byte, 300)
	buf[0] = 0xDE
	if _, err := ParseJK02CellInfo(buf, 8, ""); err == nil {
		t.Errorf("expected error on bad header")
	}
}

func TestParse_RejectsWrongFrameType(t *testing.T) {
	buf := make([]byte, 300)
	buf[0], buf[1], buf[2], buf[3] = 0x55, 0xAA, 0xEB, 0x90
	buf[4] = 0x03 // device-info, not cell-info
	if _, err := ParseJK02CellInfo(buf, 8, ""); err == nil {
		t.Errorf("expected error on non-0x02 frame")
	}
}

func TestParse_RejectsShortBuffer(t *testing.T) {
	if _, err := ParseJK02CellInfo(make([]byte, 100), 8, ""); err == nil {
		t.Errorf("expected error on short buffer")
	}
}
